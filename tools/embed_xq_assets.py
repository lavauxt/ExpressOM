#!/usr/bin/env python3
"""Embed the Quarto dashboard's runtime assets into R code.

Reads every file in tools/xq/ and writes R/xq-assets.R, where each asset
becomes an R string constant holding its gzip-compressed, base64-encoded
text. The report's <head> then carries the compressed payloads plus the
plain-text bootstrap (tools/xq/xq-bootstrap.js) that inflates them, so the
~800 KB of dashboard JavaScript/CSS costs ~1/3 of its size in the HTML.

The bootstrap itself is embedded verbatim (it is the decompressor -- it
cannot be compressed). Run this script whenever tools/xq/ changes:

    python3 tools/embed_xq_assets.py

Files in tools/vendor/ (the esbuild inputs for xq-vendor.min.js) are build
tooling, never embedded; regenerate the bundle there first if needed.
"""
import base64
import hashlib
import re
import zlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
XQ_DIR = ROOT / "tools" / "xq"
OUT_FILE = ROOT / "R" / "xq-assets.R"

# order matters: the bootstrap is plain, then vendor (provides fflate for the
# later assets), then the modules in dependency order
ASSETS = [
    ("xq-vendor.min.js", "js"),
    ("xq-core.js", "js"),
    ("xq-widgets.js", "js"),
    ("xq-scatter.js", "js"),
    ("xq-charts.js", "js"),
    ("xq-views.js", "js"),
    ("xq.css", "css"),
]
BOOTSTRAP = "xq-bootstrap.js"


def r_string_b64(b: bytes) -> list:
    """Base64 bytes as R string literals, comma-separated for paste0()."""
    b64 = base64.b64encode(b).decode("ascii")
    lines = [b64[i:i + 72] for i in range(0, len(b64), 72)] or [""]
    return [f'"{chunk}"' for chunk in lines]


def main() -> int:
    bootstrap = (XQ_DIR / BOOTSTRAP).read_bytes()
    chunks = [
        "# xq-assets.R -- auto-generated by tools/embed_xq_assets.py; DO NOT EDIT.",
        "#",
        "# The Quarto dashboard's runtime assets (tools/xq/*.js, tools/xq/xq.css)",
        "# embedded as R string constants so the package needs no inst/ directory",
        "# and reports stay self-contained. Each asset is zlib-compressed (the same",
        "# wrap R's memCompress(type = 'gzip') produces) and",
        "# base64-encoded; the report's <head> carries the payloads plus the plain",
        f"# bootstrap, which inflates them at open time (see {BOOTSTRAP}).",
        "# Regenerate with:  python3 tools/embed_xq_assets.py",
        "",
        "#' Embedded Quarto dashboard assets (compressed)",
        "#'",
        "#' Named list of gzip+base64 payloads, one per runtime asset in",
        "#' tools/xq/. Keys are file names, values are lists with `b64` (the",
        "#' payload) and `sha` (hex digest of the uncompressed bytes). The",
        "#' bootstrap is stored separately, plain.",
        "#' @keywords internal",
        ".xq_asset_data <- list(",
    ]
    total_raw = total_comp = 0
    for idx, (name, kind) in enumerate(ASSETS):
        raw = (XQ_DIR / name).read_bytes()
        comp = zlib.compress(raw, 9)
        total_raw += len(raw)
        total_comp += len(comp)
        sha = hashlib.sha256(raw).hexdigest()
        const = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_")
        b64_lines = r_string_b64(comp)
        chunks.append(f"  {const} = list(")
        chunks.append("    b64 = paste0(")
        for i, line in enumerate(b64_lines):
            comma = "," if i < len(b64_lines) - 1 else ""
            chunks.append(f"      {line}{comma}")
        chunks.append("    ),")
        chunks.append(f'    sha = "{sha}", kind = "{kind}", file = "{name}"')
        # no trailing comma after the last record: R's parser accepts one but
        # evaluation fails with "argument N is empty"
        chunks.append("  )" + ("," if idx < len(ASSETS) - 1 else ""))
    chunks.append(")")
    chunks.append("")
    chunks.append("#' The plain-text asset bootstrap (decompressor), embedded verbatim")
    chunks.append("#' @keywords internal")
    # paste(..., sep = "\n") so the constant is ONE string, not a vector:
    # consumers paste0() around it, and a vector would splice into one
    # <script> block per line
    chunks.append('.xq_bootstrap_js <- paste(')
    boot_lines = bootstrap.decode("utf-8").splitlines()
    for i, line in enumerate(boot_lines):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        comma = "," if i < len(boot_lines) - 1 else ""
        chunks.append(f'  "{esc}"{comma}')
    chunks.append('  , sep = "\\n"')
    chunks.append(")")
    chunks.append("")
    OUT_FILE.write_text("\n".join(chunks) + "\n", encoding="utf-8")
    # structural self-check: an empty trailing argument (", )") parses in R
    # but fails at load time with "argument N is empty" -- exactly the class
    # of bug a paren-balance checker cannot see
    written = OUT_FILE.read_text(encoding="utf-8")
    for pat, what in ((r",\s*\)", "empty trailing argument"),
                      (r"paste0\(\s*\)", "empty paste0"),
                      (r"=\s*,", "empty argument value")):
        if re.search(pat, written):
            print(f"SELF-CHECK FAILED: generated file contains {what} ({pat})",
                  file=sys.stderr)
            return 1
    print(f"wrote {OUT_FILE}")
    print(f"  {len(ASSETS)} compressed assets: {total_raw:,} -> {total_comp:,} bytes "
          f"({total_comp / total_raw:.1%}); b64 ~{int(total_comp * 1.374):,}")
    print(f"  bootstrap plain: {len(bootstrap):,} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
