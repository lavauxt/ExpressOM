#' Write an embedded template to a file and return its path
#' @param name One of "expressom_report.Rmd", "dte_dtu_report.Rmd"
#' @param dest Destination file path
#' @return The destination path (invisibly)
#' @keywords internal
.write_embedded_template <- function(name, dest) {
  text <- switch(
    name,
    "expressom_report.Rmd" = .expressom_report_rmd_text(),
    "dte_dtu_report.Rmd"   = .dte_dtu_report_rmd_text(),
    stop("Unknown embedded template: ", name, call. = FALSE)
  )
  writeLines(text, dest, useBytes = TRUE)
  invisible(dest)
}

